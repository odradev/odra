/// A function of a module impl block or of a trait: an entry point, or an `#[odra(offchain)]`
/// function run on the host. Validated when read, see [FnIR::try_new_impl]: its name and
/// argument names are not reserved, every argument is `name: Type`, its `#[odra(..)]`
/// attributes parse, and `offchain` fits the function and the impl block it is in.
pub struct FnIR {
    code: FnCode,
    /// The `name: Type` arguments, the receiver aside.
    args: Vec<FnArgIR>,
    odra_attrs: OdraAttrs,
    fn_type: FnType,
    delegation: Option<Delegation>
}

/// The function as written, in an impl block or in a trait.
enum FnCode {
    Impl(syn::ImplItemFn),
    Trait(syn::TraitItemFn)
}

impl FnCode {
    fn sig(&self) -> &syn::Signature {
        match self {
            FnCode::Impl(code) => &code.sig,
            FnCode::Trait(code) => &code.sig
        }
    }

    fn attrs(&self) -> &[syn::Attribute] {
        match self {
            FnCode::Impl(code) => &code.attrs,
            FnCode::Trait(code) => &code.attrs
        }
    }
}

/// What the impl block a function is read from is, for the checks that depend on it.
#[derive(Clone, Copy, Default)]
pub struct ImplContext {
    /// `impl Trait for Module`: every function is an entry point, and the trait is implemented
    /// by the contract ref too.
    pub is_trait_impl: bool,
    /// `#[odra::module(factory = on)]`.
    pub is_factory: bool
}

/// Where a function generated by a `delegate!` block forwards its call.
pub struct Delegation {
    /// The submodule field, e.g. `self.metadata`.
    pub target: syn::ExprField,
    /// `false` if the docs were generated, so the schema description is inherited
    /// from the submodule's entry point of the same name.
    pub has_own_docs: bool
}

const PROTECTED_FUNCTIONS: [&str; 6] = [
    "new",
    "env",
    "address",
    "new_contract",
    "upgrade_child_contract",
    "batch_upgrade_child_contract"
];
const PROTECTED_ARGS: [&str; 2] = ["gas", "attached_value"];

fn validate_fn_name(name: &Ident) -> syn::Result<()> {
    if PROTECTED_FUNCTIONS.contains(&name.to_string().as_str()) {
        return Err(errors::reserved_fn_name(name));
    }
    Ok(())
}

/// An argument is `name: Type` (the receiver aside), and the name is not one every call carries.
fn validate_fn_arg(arg: &syn::FnArg) -> syn::Result<()> {
    let name = match arg {
        syn::FnArg::Receiver(_) => return Ok(()),
        syn::FnArg::Typed(syn::PatType { pat, .. }) => match pat.as_ref() {
            syn::Pat::Ident(pat) => &pat.ident,
            _ => return Err(errors::arg_without_name(arg))
        }
    };
    if PROTECTED_ARGS.contains(&name.to_string().as_str()) {
        return Err(errors::reserved_arg_name(name));
    }
    Ok(())
}

/// Functions whose wasm entry point is built by a dedicated codegen path
/// (see `AddEntryPointStmtItem`) that does not read the `#[odra(..)]` flags.
/// An attribute here would be dropped without a trace, so it is rejected instead.
const NO_ODRA_ATTRIBUTE_FUNCTIONS: [&str; 2] = [CONSTRUCTOR_NAME, UPGRADER_NAME];

fn validate_fn_attrs(fn_name: &str, attrs: &OdraAttrs) -> syn::Result<()> {
    if !NO_ODRA_ATTRIBUTE_FUNCTIONS.contains(&fn_name) {
        return Ok(());
    }
    errors::check_all(
        attrs
            .each_attribute()
            .map(|(attr, flag)| Err(errors::odra_attr_on_special_fn(attr, flag, fn_name)))
    )
}

/// `#[odra(offchain)]` is only meaningful on a read-only function of a plain module impl.
fn validate_offchain(sig: &syn::Signature, attrs: &OdraAttrs, ctx: ImplContext) -> syn::Result<()> {
    let Some(offchain_attr) = attrs.offchain_attribute() else {
        return Ok(());
    };
    let receiver = utils::syn::receiver_arg(sig);
    let is_mut = receiver.as_ref().is_some_and(|r| r.mutability.is_some());
    let (why, spanned) = if ctx.is_trait_impl {
        (OffchainMisuse::InTraitImpl, offchain_attr.to_token_stream())
    } else if ctx.is_factory {
        (OffchainMisuse::InFactory, offchain_attr.to_token_stream())
    } else if is_mut {
        (OffchainMisuse::MutReceiver, receiver.to_token_stream())
    } else if attrs.is_payable() || attrs.is_non_reentrant() {
        (
            OffchainMisuse::PayableOrNonReentrant,
            offchain_attr.to_token_stream()
        )
    } else if receiver.is_none() {
        (OffchainMisuse::NoReceiver, sig.ident.to_token_stream())
    } else {
        return Ok(());
    };
    Err(errors::offchain_misuse(
        spanned,
        &sig.ident.to_string(),
        why
    ))
}

impl TryFrom<syn::TraitItemFn> for FnIR {
    type Error = syn::Error;

    fn try_from(code: syn::TraitItemFn) -> Result<Self, Self::Error> {
        Self::try_new(FnCode::Trait(code), None)
    }
}

impl FnIR {
    /// A function of an impl block, checked.
    pub fn try_new_impl(code: syn::ImplItemFn, ctx: ImplContext) -> syn::Result<Self> {
        Self::try_new(FnCode::Impl(code), Some(ctx))
    }

    /// Runs every check of the function and reports all the errors as one. The offchain check
    /// needs the impl block's context; a trait's function has none.
    fn try_new(code: FnCode, ctx: Option<ImplContext>) -> syn::Result<Self> {
        let sig = code.sig();
        let fn_name = sig.ident.to_string();
        let odra_attrs = OdraAttrs::parse(code.attrs());
        let attr_checks = match (&odra_attrs, ctx) {
            (Ok(attrs), Some(ctx)) => errors::check_all([
                validate_fn_attrs(&fn_name, attrs),
                validate_offchain(sig, attrs, ctx)
            ]),
            (Ok(attrs), None) => validate_fn_attrs(&fn_name, attrs),
            (Err(error), _) => Err(error.clone())
        };
        errors::check_all([
            validate_fn_name(&sig.ident),
            errors::check_all(sig.inputs.iter().map(validate_fn_arg)),
            attr_checks
        ])?;
        Ok(Self::new(code, odra_attrs?))
    }

    /// A function the macro synthesized, read without its checks. An `#[odra(..)]` attribute
    /// that does not parse counts as absent.
    pub fn unchecked(code: syn::ImplItemFn) -> Self {
        let odra_attrs = OdraAttrs::parse(&code.attrs).unwrap_or_default();
        Self::new(FnCode::Impl(code), odra_attrs)
    }

    fn new(code: FnCode, odra_attrs: OdraAttrs) -> Self {
        let sig = code.sig();
        let args = sig.inputs.iter().filter_map(FnArgIR::named).collect();
        let fn_type = match sig.ident.to_string().as_str() {
            CONSTRUCTOR_NAME => FnType::Constructor,
            UPGRADER_NAME => FnType::Upgrader,
            FACTORY_NAME => FnType::Factory,
            FACTORY_UPGRADE_NAME => FnType::FactoryUpgrader,
            BATCH_FACTORY_UPGRADE_NAME => FnType::FactoryBatchUpgrader,
            _ => FnType::Regular
        };
        Self {
            code,
            args,
            odra_attrs,
            fn_type,
            delegation: None
        }
    }

    pub(super) fn delegated_to(self, target: syn::ExprField, has_own_docs: bool) -> Self {
        Self {
            delegation: Some(Delegation {
                target,
                has_own_docs
            }),
            ..self
        }
    }

    /// Generated by a `delegate!` block.
    pub fn is_delegated(&self) -> bool {
        self.delegation.is_some()
    }

    /// The function as written in an impl block; `None` for a trait's function.
    pub fn raw_impl(&self) -> Option<syn::ImplItemFn> {
        match &self.code {
            FnCode::Impl(code) => Some(code.clone()),
            FnCode::Trait(_) => None
        }
    }

    pub fn attributes(&self) -> &[syn::Attribute] {
        self.code.attrs()
    }

    pub fn docs(&self) -> Vec<String> {
        utils::syn::string_docs(self.attributes())
    }

    pub(super) fn sig(&self) -> &syn::Signature {
        self.code.sig()
    }

    pub fn name(&self) -> Ident {
        self.sig().ident.clone()
    }

    pub fn try_name(&self) -> Ident {
        format_ident!("try_{}", self.name())
    }

    pub fn try_no_ret_name(&self) -> Ident {
        format_ident!("try_{}_no_ret", self.name())
    }

    pub fn execute_name(&self) -> Ident {
        format_ident!("execute_{}", self.name())
    }

    pub fn name_str(&self) -> String {
        self.name().to_string()
    }

    pub fn fn_type(&self) -> FnType {
        self.fn_type
    }

    pub fn is_constructor(&self) -> bool {
        self.fn_type == FnType::Constructor
    }

    pub fn is_upgrader(&self) -> bool {
        self.fn_type == FnType::Upgrader
    }

    pub fn is_payable(&self) -> bool {
        self.odra_attrs.is_payable()
    }

    pub fn is_non_reentrant(&self) -> bool {
        self.odra_attrs.is_non_reentrant()
    }

    pub fn is_offchain(&self) -> bool {
        self.odra_attrs.is_offchain()
    }

    pub fn args(&self) -> &[FnArgIR] {
        &self.args
    }

    pub fn has_args(&self) -> bool {
        !self.args.is_empty()
    }

    pub fn return_type(&self) -> syn::ReturnType {
        self.sig().output.clone()
    }

    /// `-> OdraResult<Ret>`, with `Ret` `()` when the function returns nothing.
    pub fn try_return_type(&self) -> syn::ReturnType {
        let ty: syn::Type = match self.return_type() {
            syn::ReturnType::Default => parse_quote!(()),
            syn::ReturnType::Type(_, ty) => *ty
        };
        parse_quote!(-> OdraResult<#ty>)
    }

    pub fn generics(&self) -> &syn::Generics {
        &self.sig().generics
    }

    pub fn is_mut(&self) -> bool {
        let receiver = utils::syn::receiver_arg(self.sig());
        receiver.map(|r| r.mutability.is_some()).unwrap_or_default()
    }

    /// The submodule field a `delegate!`-generated function with no docs of its own forwards
    /// to; its schema description is inherited from that submodule's entry point.
    pub fn inherits_description_from(&self) -> Option<&syn::ExprField> {
        self.delegation
            .as_ref()
            .filter(|delegation| !delegation.has_own_docs)
            .map(|delegation| &delegation.target)
    }
}

/// A `name: Type` argument of an entry point. Only such arguments reach here: a pattern in
/// place of the name is rejected when the function is read.
#[derive(Clone)]
pub struct FnArgIR {
    ident: Ident,
    code: syn::PatType
}

impl FnArgIR {
    /// The argument, when it is `name: Type`.
    fn named(arg: &syn::FnArg) -> Option<Self> {
        let syn::FnArg::Typed(code) = arg else {
            return None;
        };
        let syn::Pat::Ident(pat) = code.pat.as_ref() else {
            return None;
        };
        Some(Self {
            ident: pat.ident.clone(),
            code: code.clone()
        })
    }

    pub fn raw(&self) -> syn::FnArg {
        syn::FnArg::Typed(self.code.clone())
    }

    pub fn name(&self) -> Ident {
        self.ident.clone()
    }

    pub fn name_str(&self) -> String {
        self.ident.to_string()
    }

    /// The name with the span of the type: for a use of the value whose bound error should point
    /// at the type, as every other error about the argument does.
    pub fn name_spanned_as_type(&self) -> Ident {
        Ident::new(&self.ident.to_string(), self.code.ty.span())
    }

    pub fn ty(&self) -> &syn::Type {
        &self.code.ty
    }

    pub fn name_and_ty(&self) -> (String, syn::Type) {
        (self.name_str(), self.ty().clone())
    }

    pub fn is_ref(&self) -> bool {
        utils::syn::is_ref(self.ty())
    }
}
