//! Dapp information modules.
//!
//! A dapp is usually made of several contracts. A [`DappRegistry`] groups them: it keeps the dapp's
//! [`DappMetadata`] and the list of contracts that belong to the dapp. Every member contract implements
//! [`DappContract`] and points back to its registry, so the registry can verify each contract it adds.
//!
//! The base modules, [`DappRegistryBase`] and [`DappContractBase`], do not check who calls them. Compose
//! them with an access module such as [`Ownable`](crate::access::Ownable) or
//! [`AccessControl`](crate::access::AccessControl), as [`OwnedDappRegistry`] does.
//!
//! The dapp data lives under named keys and dictionaries (`__dapp_registry`, `__dapp_name`,
//! `__dapp_contracts`, ..., see [`storage`]), so it can be read from the chain without calling the
//! contracts. A contract composing [`DappRegistryBase`] calls its `init`, which creates the dictionaries.
//!
//! A factory contract generated by `#[odra::module(factory = on)]` implements the
//! [`DappContract`] interface on its own: the holder of the factory access points it to a registry with
//! `set_factory_dapp_registry`, see `odra::factory_dapp`. Registering the contracts a factory deploys
//! stays with the code that calls the factory, because anyone may call `new_contract`.
