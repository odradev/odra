//! Dapp information modules.
//!
//! A dapp is usually made of several contracts. A [`DappRegistry`] groups them: it keeps the dapp's
//! [`DappMetadata`] and the list of contracts that belong to the dapp. The registry alone decides which
//! contracts belong to it and does not call them, so any contract can be added, including one deployed
//! before the registry, and a contract can belong to several dapps. A contract registered as a
//! registrar may add other contracts.
//!
//! A contract may confirm the membership from its side by implementing [`DappMember`], whose
//! `recognizes_dapp_registry` says whether the contract considers itself part of a dapp. Users and
//! explorers check it off-chain against the registry's list. [`DappMemberBase`] implements it.
//!
//! The base modules, [`DappRegistryBase`] and [`DappMemberBase`], do not check who calls them. Compose
//! them with an access module such as [`Ownable`](crate::access::Ownable) or
//! [`AccessControl`](crate::access::AccessControl), as [`OwnedDappRegistry`] does.
//!
//! The dapp data of a contract lives in one dictionary under the `__dapp` named key (`__dapp->name`,
//! `__dapp->registrars-><address>`, ..., see [`storage`]), so it can be read from the chain without
//! calling the contracts. A contract composing [`DappRegistryBase`] or [`DappMemberBase`] calls its
//! `init`, which creates the dictionary.
//!
//! A factory contract generated by `#[odra::module(factory = on)]` can add the contracts it creates to a
//! dapp: the holder of the factory access restricts `new_contract` to one creator with
//! `set_factory_creator` and points the factory to a registry with `set_factory_dapp_registry`, where
//! the factory is a registrar. See `odra::factory_dapp`.
