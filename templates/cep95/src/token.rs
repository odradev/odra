use odra::{casper_types::{bytesrepr::Bytes, U256}, prelude::*};
use odra_modules::access::Ownable;
use odra_modules::cep95::{CEP95Interface, Cep95, Error};

/// A module definition. Each module struct consists Vars and Mappings
/// or/and another modules.
#[odra::module]
pub struct MyToken {
    /// A sub-module that implements the CEP-95 token standard.
    token: SubModule<Cep95>,
    /// A sub-module that keeps the owner of the contract: the only account allowed to mint.
    ownable: SubModule<Ownable>,
}

/// Module implementation.
///
/// To generate entrypoints,
/// an implementation block must be marked as #[odra::module].
#[odra::module]
impl MyToken {

    /// Initializes the contract with the given parameters. The deployer becomes the owner.
    pub fn init(&mut self, name: String, symbol: String) {
        self.token.name.set(name);
        self.token.symbol.set(symbol);
        let deployer = self.env().caller();
        self.ownable.init(deployer);
    }

    /// Returns the owner of the contract.
    pub fn owner(&self) -> Address {
        self.ownable.get_owner()
    }

    delegate! {
        to self.token {
            fn name(&self) -> String;
            fn symbol(&self) -> String;
            fn balance_of(&self, owner: Address) -> U256;
            fn owner_of(&self, token_id: U256) -> Option<Address>;
            fn safe_transfer_from(&mut self, from: Address, to: Address, token_id: U256, data: Option<Bytes>);
            fn transfer_from(&mut self, from: Address, to: Address, token_id: U256);
            fn approve(&mut self, spender: Address, token_id: U256);
            fn revoke_approval(&mut self, token_id: U256);
            fn approved_for(&self, token_id: U256) -> Option<Address>;
            fn approve_for_all(&mut self, operator: Address);
            fn revoke_approval_for_all(&mut self, operator: Address);
            fn is_approved_for_all(&self, owner: Address, operator: Address) -> bool;
            fn token_metadata(&self, token_id: U256) -> Vec<(String, String)>;
        }
    }

    /// Mints a new token with the given ID and metadata to the specified address.
    /// Only the contract owner can call this function.
    pub fn mint(&mut self, to: Address, token_id: U256, metadata: Vec<(String, String)>) {
        // `raw_mint` checks nothing: without this line anyone could mint.
        self.ownable.assert_owner(&self.env().caller());
        self.token.raw_mint(to, token_id, metadata);
    }

    /// Burns the token with the given ID.
    /// Only the token owner can call this function.
    /// This function will remove the token from the owner's balance and delete its metadata.
    pub fn burn(&mut self, token_id: U256) {
        // `raw_burn` checks nothing: without this check anyone could burn any token.
        if self.token.owner_of(token_id) != Some(self.env().caller()) {
            self.env().revert(Error::NotAnOwnerOrApproved);
        }
        self.token.raw_burn(token_id);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use odra::host::Deployer;
    use odra_modules::access::errors::Error as OwnableError;

    fn setup() -> (odra::host::HostEnv, MyTokenHostRef) {
        let env = odra_test::env();
        // To test a module we need to deploy it. Autogenerated `MyTokenInitArgs`
        // implements `InitArgs` trait and `MyToken` implements `Deployer` trait,
        // so we can use it to deploy the module.
        let init_args = MyTokenInitArgs {
            name: "MyToken".to_string(),
            symbol: "MT".to_string(),
        };
        let token = MyToken::deploy(&env, init_args);
        (env, token)
    }

    #[test]
    fn the_owner_mints() {
        let (env, mut token) = setup();
        let alice = env.get_account(1);

        token.mint(alice, U256::one(), vec![]);
        assert_eq!(token.owner_of(U256::one()), Some(alice));

        // Nobody else can mint.
        env.set_caller(alice);
        assert_eq!(
            token.try_mint(alice, U256::from(2), vec![]),
            Err(OwnableError::CallerNotTheOwner.into())
        );
    }

    #[test]
    fn the_token_owner_burns() {
        let (env, mut token) = setup();
        let alice = env.get_account(1);
        token.mint(alice, U256::one(), vec![]);

        // Not even the owner of the contract can burn somebody else's token.
        assert_eq!(
            token.try_burn(U256::one()),
            Err(Error::NotAnOwnerOrApproved.into())
        );

        env.set_caller(alice);
        token.burn(U256::one());
        assert_eq!(token.owner_of(U256::one()), None);
    }
}
